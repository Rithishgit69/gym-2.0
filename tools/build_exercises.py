#!/usr/bin/env python3
"""Generate js/exercises.js from the hasaneyldrm/exercises-dataset JSON,
plus sharp start/end photos from yuhonas/free-exercise-db (public domain).

Only the exercises referenced in js/program.js are exported. Media is NOT
copied: the app loads it from the source repos (pinned commits) and caches it
on the phone for offline use.

Usage:
    python3 tools/build_exercises.py path/to/exercises.json [path/to/free-exercise-db.json]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SHA = "7455efae41b330c265e7cd4b78dfa848e7ce5ebd"
PHOTO_SHA = "f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5"


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    sha = DEFAULT_SHA
    photo_db = {}
    if len(sys.argv) > 2:
        photo_db = {x["id"]: x for x in json.loads(Path(sys.argv[2]).read_text(encoding="utf-8"))}
    photo_map = json.loads((ROOT / "tools" / "photo_map.json").read_text(encoding="utf-8"))
    program = (ROOT / "js" / "program.js").read_text(encoding="utf-8")
    ids = sorted(set(re.findall(r"'(\d{4})'", program)))

    data = {x["id"]: x for x in json.loads(src.read_text(encoding="utf-8"))}
    missing = [i for i in ids if i not in data]
    if missing:
        sys.exit(f"IDs not found in dataset: {missing}")

    out = {}
    for i in ids:
        x = data[i]
        steps = x.get("instruction_steps", {}).get("en") or [x["instructions"]["en"]]
        out[i] = {
            "name": x["name"],
            "target": x["target"],
            "secondary": x.get("secondary_muscles", []),
            "equipment": x["equipment"],
            "bodyPart": x["body_part"],
            "steps": [s.strip() for s in steps if s.strip()],
            "gif": x["gif_url"],
            "img": x["image"],
        }
        pid = photo_map.get(i)
        if pid:
            if photo_db and pid not in photo_db:
                sys.exit(f"free-exercise-db ID not found: {pid}")
            imgs = photo_db[pid]["images"] if photo_db else [f"{pid}/0.jpg", f"{pid}/1.jpg"]
            out[i]["photos"] = imgs[:2]

    base = f"https://raw.githubusercontent.com/hasaneyldrm/exercises-dataset/{sha}/"
    photo_base = f"https://raw.githubusercontent.com/yuhonas/free-exercise-db/{PHOTO_SHA}/exercises/"
    js = (
        "/* Generated by tools/build_exercises.py. Do not edit by hand.\n"
        "   Source: github.com/hasaneyldrm/exercises-dataset (data: MIT).\n"
        "   Animations: © Gym visual (gymvisual.com), loaded from the dataset repo, not redistributed.\n"
        "   Photos: github.com/yuhonas/free-exercise-db (Unlicense, public domain). */\n"
        f"window.MEDIA_BASE = {json.dumps(base)};\n"
        f"window.PHOTO_BASE = {json.dumps(photo_base)};\n"
        f"window.EXERCISES = {json.dumps(out, ensure_ascii=False, indent=1)};\n"
    )
    (ROOT / "js" / "exercises.js").write_text(js, encoding="utf-8")
    n_photos = sum(1 for v in out.values() if "photos" in v)
    print(f"Wrote {len(out)} exercises ({n_photos} with photos) to js/exercises.js")


if __name__ == "__main__":
    main()
